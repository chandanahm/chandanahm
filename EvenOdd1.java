//wjp to check given number is even or odd without using modules operator 
class EvenOdd1
{   
   public static void main(String[] args) 
    {
      int n=5;
      if(n/2*2 == n)
      {
        System.out.println(n+" even");
       }
      else
      {
       System.out.println(n+" odd");
       }
}
}